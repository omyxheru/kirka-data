"""Build a dated markdown route map of api2.kirka.io from the public Swagger (docs-json) + our probe results.
Usage: python tools/api2_routes.py kirka-api/api2/docs-json-YYYYMMDD.json docs/api2-routes-YYYYMMDD.md
Never overwrites an existing file (docs are append-only)."""
import json, sys, os, collections
spec, out = sys.argv[1], sys.argv[2]
if os.path.exists(out): sys.exit(f"{out} exists - docs are append-only, pick a new dated name")
d = json.load(open(spec, encoding='utf-8'))
pf = os.path.join(os.path.dirname(spec), 'probe.json')
probe = {p[2]: p[0] for p in json.load(open(pf, encoding='utf-8'))} if os.path.exists(pf) else {}
def body(o):
    s = o.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema', {})
    return s.get('$ref', '').split('/')[-1] or ('inline' if s else '')
by = collections.defaultdict(list)
for path, m in d['paths'].items():
    for meth, o in m.items():
        if not isinstance(o, dict): continue
        op = o.get('operationId', '?_?'); c, name = op.split('_', 1) if '_' in op else ('?', op)
        ps = ', '.join(p['name'] for p in o.get('parameters', []) if p.get('in') != 'header')
        hs = ', '.join(p['name'] for p in o.get('parameters', []) if p.get('in') == 'header')
        by[c].append((meth.upper(), path, name, 'yes' if o.get('security') else 'no', ps, body(o), hs, probe.get(op, '')))
L = [f"# api2.kirka.io — full route map ({os.path.basename(spec)})", "",
     "Generated by `tools/api2_routes.py` from the PUBLIC Swagger `GET https://api2.kirka.io/api/docs-json`.",
     "`auth` = the spec marks it as needing a bearer token. `probe` = HTTP status from our no-auth probe "
     "(`kirka-api/api2/probe.json`; blank = never probed; 400 usually just means it needs a body).",
     "KatController = staff panel: xip said leave KAT for now (2026-11-15) - listed for completeness only.", "",
     f"**{sum(map(len, by.values()))} routes in {len(by)} controllers.**", ""]
for c, rs in sorted(by.items(), key=lambda x: (x[0].startswith('Kat'), -len(x[1]))):
    L += [f"## {c} ({len(rs)})", "", "| method | path | operation | auth | params | body | headers | probe |", "|---|---|---|---|---|---|---|---|"]
    L += [f"| {a} | `{b}` | {n} | {s} | {p} | {bd} | {h} | {pr} |" for a, b, n, s, p, bd, h, pr in rs] + [""]
schemas = d.get('components', {}).get('schemas', {})
L += [f"## Request body schemas ({len(schemas)})", ""]
for n, s in schemas.items():
    props = s.get('properties', {})
    L.append(f"- **{n}**: " + ', '.join(f"`{k}`:{v.get('type', v.get('$ref', '').split('/')[-1])}" for k, v in props.items()))
open(out, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('wrote', out, sum(map(len, by.values())), 'routes,', len(schemas), 'schemas')
